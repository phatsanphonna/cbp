package main

import (
	"context"
	"errors"
	"flag"
	"fmt"
	"log/slog"
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"strconv"
	"strings"
	"time"
)

const agentServiceName = "cbp-agent.service"
const managedUnitHeader = "# Generated by cbp-agent -install-service\n"

func checkAgentServiceSupport() error {
	if runtime.GOOS != "linux" || os.Geteuid() != 0 {
		return errors.New("-install-service requires root on a Linux host running systemd")
	}
	if _, err := os.Stat("/run/systemd/system"); err != nil {
		return errors.New("-install-service requires a running systemd service manager")
	}
	_, err := exec.LookPath("systemctl")
	return err
}

func installAgentService(ctx context.Context, flags *flag.FlagSet) error {
	executable, err := os.Executable()
	if err != nil {
		return err
	}
	executable, err = filepath.EvalSymlinks(executable)
	if err != nil {
		return err
	}
	unit, err := agentServiceUnit(executable, flags)
	if err != nil {
		return err
	}
	if err := writeAgentService(filepath.Join("/etc/systemd/system", agentServiceName), unit); err != nil {
		return err
	}
	ctx, cancel := context.WithTimeout(ctx, 60*time.Second)
	defer cancel()
	for _, args := range [][]string{{"daemon-reload"}, {"enable", agentServiceName}, {"restart", agentServiceName}} {
		if output, err := exec.CommandContext(ctx, "systemctl", args...).CombinedOutput(); err != nil {
			return fmt.Errorf("systemctl %s: %w: %s", args[0], err, strings.TrimSpace(string(output)))
		}
	}
	slog.Info("systemd service enabled and started", "service", agentServiceName)
	return nil
}

func agentServiceUnit(executable string, flags *flag.FlagSet) (string, error) {
	quote := func(value string) string { return strconv.Quote(strings.ReplaceAll(value, "%", "%%")) }
	args := []string{quote(executable)}
	var pathError error
	flags.Visit(func(f *flag.Flag) {
		if pathError != nil || f.Name == "once" || f.Name == "install-service" {
			return
		}
		value := f.Value.String()
		switch f.Name {
		case "ca", "config", "credential-file":
			if value != "" {
				value, pathError = filepath.Abs(value)
			}
		}
		args = append(args, "-"+f.Name, quote(value))
	})
	if pathError != nil {
		return "", pathError
	}
	return managedUnitHeader + `[Unit]
Description=CBP host agent
Wants=network-online.target
After=network-online.target

[Service]
Type=exec
ExecStart=:` + strings.Join(args, " ") + `
UnsetEnvironment=CBP_AGENT_ENROLLMENT_CODE
Restart=on-failure
RestartSec=5s

[Install]
WantedBy=multi-user.target
`, nil
}

func writeAgentService(path, unit string) error {
	info, err := os.Lstat(path)
	if err == nil {
		if !info.Mode().IsRegular() {
			return fmt.Errorf("existing service unit is not a regular file: %s", path)
		}
		current, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if string(current) == unit {
			return nil
		}
		if !strings.HasPrefix(string(current), managedUnitHeader) {
			return fmt.Errorf("existing service unit is managed manually: %s", path)
		}
	} else if !errors.Is(err, os.ErrNotExist) {
		return err
	}

	file, err := os.CreateTemp(filepath.Dir(path), ".cbp-agent-service-*")
	if err != nil {
		return err
	}
	defer os.Remove(file.Name())
	_, writeErr := file.WriteString(unit)
	if err := errors.Join(writeErr, file.Chmod(0644), file.Close()); err != nil {
		return err
	}
	return os.Rename(file.Name(), path)
}
